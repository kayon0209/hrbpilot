"""HRBPilot 的 OAuth 2.1 授权服务器（Authorization Server）。

定位
----
它是一个**独立应用**（``app.oauth.main.create_oauth_app`` 有独立入口，可用
``uvicorn app.oauth.main:app`` 单独起进程），不是主应用的一个路由模块。ADR-0002
§2 把职责切成两半：主应用只做 Resource Server（校验令牌、给出挑战、提供元数据），
本包只做 Authorization Server（签发令牌、管理客户端与授权码）。

为什么要分开
------------
主应用承载员工敏感数据，它被攻破的爆炸半径已经很大。把签名私钥再放进去，等于让
一次普通业务漏洞同时变成"可以伪造任意令牌"。分开之后，主应用**只持有公钥**
（通过 JWKS 获取），即使它被完全攻破也签不出任何东西。

与主应用的关系
--------------
两者共享同一个数据库与同一份用户表（AS 要认证资源所有者是谁），但不共享进程、
不共享路由、不共享密钥。RS 侧通过配置的 issuer 列表信任本 AS。
"""
