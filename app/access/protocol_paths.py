"""协议级匿名路径常量 —— 被多层中间件共同引用。

为什么单独一个模块（而不是放进 ``resource_metadata`` 或 ``tokens``）
-------------------------------------------------------------------
``app/access/scopes.py`` 导入 ``app/access/middleware/rbac.py``，所以 **rbac 不能
导入任何（间接）依赖 scopes 的模块** —— 包括 ``resource_metadata``（它需要 Scope
枚举来填 ``scopes_supported``）。本模块因此刻意**零依赖**：不导入任何 app 模块，
谁都能安全引用它。

为什么值得抽成常量
------------------
认证、限流、RBAC 三层中间件各自维护一份匿名路径清单。新增一个匿名端点时漏改其中
一处，症状是"端点被拒绝，但拒绝它的是另一层" —— 本轮实施真实踩过一次：
``/.well-known/`` 只加进了认证层，请求随后被限流层以 403 "Missing user context"
拒掉，而认证层的日志显示一切正常。一个共享常量比一份人肉纪律可靠。

边界：只覆盖**协议级**匿名端点
------------------------------
各层其余匿名条目（health、webhooks、dev-users…）语义各不相同，**不合并到这里**：
合并会把某些"要求认证"的路径意外放宽成匿名，那是安全方向的变更，必须逐条审查，
不能顺手统一。本模块只承载"规范要求必须匿名"的路径。
"""

from __future__ import annotations

#: RFC 9728 / RFC 8414 的发现端点前缀（``/.well-known/oauth-protected-resource`` 等）。
#:
#: 必须匿名：客户端是在**被 401 拒绝之后**才来读它的。要凭据才能读，发现流程就
#: 死锁了 —— 要令牌才知道去哪里拿令牌。返回内容只有服务的公共配置，无租户数据。
WELL_KNOWN_PREFIX = "/.well-known/"
